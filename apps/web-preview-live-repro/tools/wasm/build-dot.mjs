// Compiles tools/wasm/dot.wat → lens/dotWasm.js (base64 module). Needs the `wabt` npm package:
//   NODE_PATH=<dir with wabt> node apps/web-preview-live-repro/tools/wasm/build-dot.mjs
import fs from 'node:fs/promises'; import path from 'node:path'; import { fileURLToPath } from 'node:url'; import { createRequire } from 'node:module';
const dir = path.dirname(fileURLToPath(import.meta.url));
const wabt = await createRequire(import.meta.url)(process.env.WABT || 'wabt')();
const mod = wabt.parseWat('dot.wat', await fs.readFile(path.join(dir, 'dot.wat'), 'utf8'), { simd: true });
const { buffer } = mod.toBinary({});
await fs.writeFile(path.join(dir, '..', '..', 'lens', 'dotWasm.js'), `// Generated by tools/wasm/build-dot.mjs from tools/wasm/dot.wat — do not edit.\nexport const DOT_WASM_BASE64 = '${Buffer.from(buffer).toString('base64')}';\n`);
console.log('dot.wasm', buffer.length, 'bytes');
